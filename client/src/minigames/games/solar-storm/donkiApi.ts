export function getRandomDonkiEpisode(seed?: number): DonkiEpisode {
  if (seed !== undefined) {
    const idx = Math.abs(seed) % DONKI_EPISODES.length;
    return DONKI_EPISODES[idx];
  }
  const idx = Math.floor(Math.random() * DONKI_EPISODES.length);
  return DONKI_EPISODES[idx];
}
